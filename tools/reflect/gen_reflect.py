#!/usr/bin/env python3
"""Generates cpp/game/game_reflect.cpp: what the Java build's tests did with
reflection on the game's classes -- Field.setInt on a static field (Scenario
setf, the input pipe's setf) and Method.invoke of a public method taking one
int (the input pipe's call) -- with reflection's rules and exceptions.

Input: the game's class files as the Java build ran them (javap).
  tools/reflect/gen_reflect.py <dir of game .class files> > cpp/game/game_reflect.cpp
"""
import os, re, subprocess, sys

classdir = sys.argv[1]
names = sorted(f[:-6] for f in os.listdir(classdir) if f.endswith('.class') and '$' not in f)
info = {}
for n in names:
    out = subprocess.run(['javap', '-p', '-cp', classdir, n], capture_output=True, text=True).stdout
    head = re.search(r'class (\S+)(?: extends (\S+))?', out)
    sup = head.group(2) if head and head.group(2) in names else None
    fields, methods = [], []
    for line in out.splitlines():
        line = line.strip().rstrip(';')
        if '(' in line:
            m = re.match(r'((?:\w+ )*)(\S+) (\w+)\((.*)\)', line)
            if m and m.group(4) == 'int':
                methods.append((m.group(1).split(), m.group(2), m.group(3)))
        else:
            m = re.match(r'((?:\w+ )*)(\S+) (\w+)(?: = .*)?$', line)
            if m and m.group(3) not in ('class',) and not line.startswith(('Compiled', '}')):
                fields.append((m.group(1).split(), m.group(2), m.group(3)))
    info[n] = (sup, fields, methods)

CPP = {'int': 'int32_t', 'long': 'int64_t', 'float': 'float', 'double': 'double'}
JNAME = {'java.lang.String': 'java.lang.String'}

def jtype(t):
    # Field.toString's type: arrays as their descriptor ([B, [[I, [Lclass_3;)
    if t.endswith('[]'):
        dims = t.count('[]'); base = t.replace('[]', '')
        prim = {'byte': 'B', 'short': 'S', 'int': 'I', 'long': 'J', 'float': 'F', 'double': 'D', 'char': 'C', 'boolean': 'Z'}
        return '[' * dims + (prim[base] if base in prim else 'L' + base + ';')
    return t

o = []
w = o.append
w('// Generated by tools/reflect/gen_reflect.py from the game\'s class files (do not edit).')
w('#include "game.h"')
w('#include "deep3d/deep3d.h"')
w('#include <functional>')
w('#include <string>')
w('')
w('namespace {')
w('template <class E>')
w('[[noreturn]] void raise(const std::string& msg, bool withMessage = true) {')
w('    jrt::Ref<E> e(new E());')
w('    if (withMessage) e->message = java::lang::String::fromUtf8(msg);')
w('    jrt::throwJava(e);')
w('}')
w('/* a failure of the reflective call itself (not of the method it calls) */')
w('template <class E>')
w('[[noreturn]] void callFailed(const std::string& msg, bool withMessage = true) {')
w('    jrt::Ref<E> e(new E());')
w('    if (withMessage) e->message = java::lang::String::fromUtf8(msg);')
w('    throw game_ReflectError{e};')
w('}')
w('std::string show(int32_t v) { return std::to_string(v); }')
w('std::string show(bool v) { return v ? "true" : "false"; }')
w('template <class T>')
w('std::string show(const T& v) { return jrt::concat(JRT_LIT(u""), v)->utf8(); }')
w('}  // namespace')
w('')
w('/** Class.forName(cls).getDeclaredField(field), setAccessible, setInt(null, value()):')
w('    the value is evaluated once the field is found, as Java\'s argument. */')
w('void game_setStaticInt(const std::string& cls, const std::string& field, const std::function<int32_t()>& value) {')
for n in names:
    sup, fields, methods = info[n]
    w(f'    if (cls == "{n}") {{')
    for mods, t, f in fields:
        static = 'static' in mods
        final = 'final' in mods
        desc = ('static ' if static else '') + ('final ' if final else '') + jtype(t) + f' field {n}.{f}'
        w(f'        if (field == "{f}") {{')
        w('            int32_t v = value();')
        w('            std::string to = " to (int)" + std::to_string(v);')
        if not static:
            w('            raise<java::lang::NullPointerException>("", false);')
        elif final:
            w(f'            raise<java::lang::IllegalAccessException>("Can not set {desc}" + to);')
        elif t in CPP:
            w(f'            {n}::{f} = {CPP[t]}(v);')
            w('            return;')
        else:
            w(f'            raise<java::lang::IllegalArgumentException>("Can not set {desc}" + to);')
        w('        }')
    w('        raise<java::lang::NoSuchFieldException>(field);')
    w('    }')
w('    raise<java::lang::ClassNotFoundException>(cls);')
w('}')
w('')
w('/** Class.forName(cls).getMethod(method, int.class).invoke(null, arg), as text:')
w('    the result ("null" for void). A failure of the call itself throws game_ReflectError,')
w('    what the method throws comes out as it is (Java: InvocationTargetException). */')
w('std::string game_callStaticInt(const std::string& cls, const std::string& method, int32_t arg) {')
for n in names:
    # public methods (int) of the class and its game superclasses, most derived first
    seen, chain, c = set(), [], n
    while c:
        for mods, ret, m in info[c][2]:
            if 'public' in mods and m not in seen:
                seen.add(m); chain.append((c, mods, ret, m))
        c = info[c][0]
    w(f'    if (cls == "{n}") {{')
    for owner, mods, ret, m in chain:
        w(f'        if (method == "{m}") {{')
        if 'static' not in mods:
            w('            callFailed<java::lang::NullPointerException>("Cannot invoke \\"Object.getClass()\\" because \\"obj\\" is null");')
        elif ret == 'void':
            w(f'            {n}::{m}(arg);')
            w('            return "null";')
        else:
            w(f'            return show({n}::{m}(arg));')
        w('        }')
    w(f'        callFailed<java::lang::NoSuchMethodException>("{n}." + method + "(int)");')
    w('    }')
w('    callFailed<java::lang::ClassNotFoundException>(cls);')
w('}')
print('\n'.join(o))
