// Generates cpp/jrt/jrt_unicode.cpp: java.lang.Character's answers for every
// char (and String's case mapping for every code point) from the running JDK,
// so jrt matches Java exactly. Run: java GenUnicode.java > ../../cpp/jrt/jrt_unicode.cpp
import java.util.*;
import java.util.function.IntPredicate;

public class GenUnicode {
    static StringBuilder o = new StringBuilder();

    static void ranges(String name, IntPredicate p) {
        List<int[]> r = new ArrayList<>();
        for (int c = 0; c < 0x10000; c++) {
            if (!p.test(c)) continue;
            int s = c;
            while (c + 1 < 0x10000 && p.test(c + 1)) c++;
            r.add(new int[]{s, c});
        }
        o.append("const Range ").append(name).append("[] = {");
        int i = 0;
        for (int[] x : r) o.append(i++ % 6 == 0 ? "\n    " : " ").append(String.format("{0x%04X, 0x%04X},", x[0], x[1]));
        o.append("\n};\n\n");
    }

    static String u16(String s) {
        StringBuilder b = new StringBuilder("u\"");
        for (char c : s.toCharArray()) b.append(String.format("\\x%04X", (int) c));
        // avoid a following hex digit continuing the escape: every char is escaped
        return b.append('"').toString();
    }

    public static void main(String[] a) {
        o.append("// Generated by tools/unicode/GenUnicode.java from OpenJDK ")
         .append(Runtime.version()).append(" (do not edit): java.lang.Character's\n")
         .append("// classification and case mapping, and String's per-code-point case\n")
         .append("// mapping (root locale), exactly as Java answers them.\n")
         .append("#include \"jrt_unicode.h\"\n\nnamespace jrt::unicode {\nnamespace {\n\n");
        ranges("kDigit", c -> Character.isDigit((char) c));
        ranges("kLetter", c -> Character.isLetter((char) c));
        ranges("kLetterOrDigit", c -> Character.isLetterOrDigit((char) c));
        ranges("kWhitespace", c -> Character.isWhitespace((char) c));
        ranges("kUpper", c -> Character.isUpperCase((char) c));
        ranges("kLower", c -> Character.isLowerCase((char) c));
        // char -> char maps (only where they differ)
        for (String kind : new String[]{"Upper", "Lower"}) {
            o.append("const CharMap kTo").append(kind).append("[] = {");
            int i = 0;
            for (int c = 0; c < 0x10000; c++) {
                char m = kind.equals("Upper") ? Character.toUpperCase((char) c) : Character.toLowerCase((char) c);
                if (m != c) o.append(i++ % 6 == 0 ? "\n    " : " ").append(String.format("{0x%04X, 0x%04X},", c, (int) m));
            }
            o.append("\n};\n\n");
        }
        o.append("const DigitEntry kDigitValue[] = {");
        int i = 0;
        for (int c = 0; c < 0x10000; c++) {
            int d = Character.digit((char) c, 36);
            if (d >= 0) o.append(i++ % 6 == 0 ? "\n    " : " ").append(String.format("{0x%04X, %d},", c, d));
        }
        o.append("\n};\n\n");
        // String case mapping per code point, context-free (Final_Sigma is handled in code)
        for (String kind : new String[]{"Upper", "Lower"}) {
            o.append("const StringMap kString").append(kind).append("[] = {");
            i = 0;
            for (int cp = 0; cp <= 0x10FFFF; cp++) {
                if (cp >= 0xD800 && cp <= 0xDFFF) continue;
                String s = new String(Character.toChars(cp));
                String m = kind.equals("Upper") ? s.toUpperCase(Locale.ROOT) : s.toLowerCase(Locale.ROOT);
                if (!m.equals(s)) o.append(i++ % 3 == 0 ? "\n    " : " ").append(String.format("{0x%05X, %s},", cp, u16(m)));
            }
            o.append("\n};\n\n");
        }
        o.append("}  // namespace\n\n#include \"jrt_unicode_impl.inc\"\n\n}  // namespace jrt::unicode\n");
        System.out.print(o);
    }
}
