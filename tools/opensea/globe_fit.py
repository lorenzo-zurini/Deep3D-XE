#!/usr/bin/env python3
"""Open Sea's planet: lays the game's 200 stations onto a sphere.

The map (stations.txt: x, y on a 0..100 square) becomes the whole planet.
No flat map fits a sphere exactly, so the stations are placed to keep each
one's distances to its 8 nearest neighbours as close as possible to the
map's (in ratio), while a weak spreading force keeps them covering the
globe about as evenly as they cover the map. It starts from the equal-area
octahedral folding of the square. Result (2026-10-30): 80% of neighbour
distances within -7%..+13% of the map's, no large empty ocean.

    tools/opensea/globe_fit.py <game jar> > cpp/deep3d/OpenSeaGlobe.inc
"""
import math, sys, zipfile
import numpy as np

K, LAM, ITERS = 8, 0.2, 6000


def stations(jar):
    text = zipfile.ZipFile(jar).read('data/txt/stations.txt').decode('latin1')
    out = []
    for rec in text.replace('\n', '').split(';'):
        p = [x.strip() for x in rec.split(',')]
        if len(p) >= 5:
            out.append((int(p[2]), int(p[3])))
    return np.array(out, float)


def octa(u, v):
    """the square [-1,1]^2 onto the sphere, equal-area (Clarberg 2008)"""
    au, av = abs(u), abs(v)
    d = 1 - (au + av)
    r = 1 - abs(d)
    phi = math.pi / 4 if r == 0 else ((av - au) / r + 1) * math.pi / 4
    z = math.copysign(1 - r * r, d) if d != 0 else 0.0
    s = r * math.sqrt(max(0, 2 - r * r))
    return np.array([s * math.copysign(1, u) * math.cos(phi), s * math.copysign(1, v) * math.sin(phi), z])


def fit(xy):
    n = len(xy)
    X = np.array([octa(*((p / 100) * 2 - 1)) for p in xy])
    flat = np.sqrt(((xy[:, None, :] - xy[None, :, :]) ** 2).sum(-1))
    target = flat * math.sqrt(4 * math.pi / 1e4)        # the map's area is the sphere's
    nn = np.argsort(flat + np.eye(n) * 1e9, 1)[:, :K]
    I, J = np.repeat(np.arange(n), K), nn.ravel()
    sig = 1.5 * math.sqrt(4 * math.pi / n)                # the spreading force's reach
    for it in range(ITERS):
        D = np.arccos(np.clip((X[I] * X[J]).sum(1), -1, 1))
        lg = np.log(np.maximum(D, 1e-6) / target[I, J])
        w = (lg / np.maximum(D, 1e-6) / np.maximum(np.sin(D), 1e-6))[:, None]
        G = np.zeros_like(X)
        np.add.at(G, I, -w * X[J])
        np.add.at(G, J, -w * X[I])
        A = np.arccos(np.clip(X @ X.T, -1, 1))
        np.fill_diagonal(A, 10)
        e = np.exp(-(A / sig) ** 2)
        coef = e * (2 * A / sig ** 2) / np.maximum(np.sin(A), 1e-6)
        np.fill_diagonal(coef, 0)
        G += LAM * (coef @ X)
        G -= (G * X).sum(1, keepdims=True) * X
        step = 0.004 * (1 - it / ITERS) + 0.0005
        X -= step * G / (np.linalg.norm(G, axis=1).max() + 1e-12)
        X /= np.linalg.norm(X, axis=1, keepdims=True)
    return X


if __name__ == '__main__':
    xy = stations(sys.argv[1])
    X = fit(xy)
    print('// Generated by tools/opensea/globe_fit.py from the game\'s stations.txt: do not edit.')
    print('// Each station (in stations.txt order): its map x, y (to check the order) and')
    print('// where it stands on the planet, as a unit vector.')
    print('static const struct { int x, y; double p[3]; } kGlobe[] = {')
    for (x, y), p in zip(xy, X):
        print('    {%d, %d, {%.15f, %.15f, %.15f}},' % (x, y, *p))
    print('};')
